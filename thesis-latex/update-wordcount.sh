#!/bin/bash
# Regenerate the title-page word count from the complete thesis source.

set -euo pipefail

THESIS_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
TEXCOUNT_BIN=${TEXCOUNT_BIN:-$(command -v texcount || true)}
OUTPUT_FILE="$THESIS_ROOT/thesis-wordcount.tex"

if [[ -z "$TEXCOUNT_BIN" || ! -x "$TEXCOUNT_BIN" ]]; then
  echo "ERROR: texcount is not available on PATH" >&2
  exit 1
fi

# Count prose, headings and captions. Recursive includes bring in all chapters
# and the appendices placed at the end of Project.tex. Equations and float
# counters are not counted as words.
count=$(
  cd "$THESIS_ROOT"
  "$TEXCOUNT_BIN" -inc '-sum=1,1,1,0,0,0,0' -1 Project.tex 2>&1 \
    | awk '/^[0-9]+$/ { count = $0 } END { print count }'
)
[[ "$count" =~ ^[0-9]+$ ]]

formatted=$(perl -e '
  my $number = shift;
  1 while $number =~ s/^(-?\d+)(\d{3})/$1,$2/;
  print $number;
' "$count")

content=$(printf '%s\n%s' \
  '% Generated by update-wordcount.sh. Do not edit manually.' \
  "\\wordcount{$formatted}")

if [[ ! -f "$OUTPUT_FILE" ]] || [[ "$(<"$OUTPUT_FILE")" != "$content" ]]; then
  printf '%s\n' "$content" > "$OUTPUT_FILE"
fi

echo "wordcount=$formatted"
